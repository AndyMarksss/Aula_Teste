### Repetição com While

contador = 0

### O loop while é uma estrutura de controle de fluxo que permite executar um bloco de código repetidamente enquanto uma condição for verdadeira. Neste exemplo, o loop while continuará a imprimir "Fernando" na tela enquanto a variável contador for menor que 3. A cada iteração, o contador é incrementado em 1, garantindo que o loop seja executado exatamente 3 vezes.
while contador < 3:
    print ('Fernando') 
    contador += 1